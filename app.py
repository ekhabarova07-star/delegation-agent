def classify_delegation_experience(text):
    text_lower = text.lower()
    rarely_kw = ["редко", "не делегирую", "проще сделать сам", "проще самой", "чаще сам", "чаще сама", "нет времени", "некогда объяснять", "быстрее самому", "быстрее самой", "не успеваю", "мало делегирую"]
    regularly_kw = ["регулярно", "часто делегирую", "постоянно делегирую", "всегда делегирую", "много делегирую"]
    for kw in rarely_kw:
        if kw in text_lower:
            return "rarely"
    for kw in regularly_kw:
        if kw in text_lower:
            return "regularly"
    return "sometimes"

def current_step_key():
    return STEP_KEYS[st.session_state.step_index]

def get_system_prompt():
    key = current_step_key()
    cfg = STEPS[key]

    if key == 0 and not st.session_state.task_given:
        user_messages = [m for m in st.session_state.messages if m["role"] == "user"]
        if user_messages:
            exp_type = classify_delegation_experience(user_messages[-1]["content"])
            if exp_type == "rarely":
                return cfg["teach_rarely"]
            elif exp_type == "regularly":
                return cfg["teach_regularly"]
            else:
                return cfg["teach_sometimes"]
        return cfg["teach_rarely"]

    if st.session_state.task_given and cfg.get("check"):
        return cfg["check"]
    return cfg.get("teach") or cfg.get("teach_rarely")

